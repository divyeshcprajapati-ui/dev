        <h2>1. Overview</h2>
        <p>B2B Hub ("we", "our", or "us") provides wholesale registration, quotation negotiation, and B2B customer management tools for merchants on the Shopify platform. This Privacy Policy describes how we collect, store, and process personal information when you install and use our Shopify application.</p>

        <h2>2. Information We Collect</h2>
        <p>To provide our services, we collect and process the following categories of information upon merchant authorization:</p>
        <ul>
            <li><strong>Merchant Information:</strong> Shopify store domain, store name, email address, and active plan selection.</li>
            <li><strong>Customer & Wholesale Applicant Information:</strong> Contact names, email addresses, phone numbers, shipping/billing addresses, business document attachments, and Tax/GSTIN numbers submitted via wholesale forms.</li>
            <li><strong>Quotation Data:</strong> Requested products, proposed quantities, quoted pricing, discounts, and order negotiation timestamps.</li>
        </ul>

        <h2>3. How We Use Information</h2>
        <p>Collected information is used exclusively to:</p>
        <ul>
            <li>Enable merchants to review, verify, and approve B2B wholesale applications.</li>
            <li>Synchronize approved customers with Shopify Companies and Locations.</li>
            <li>Facilitate single and multi-item wholesale quotation requests and checkouts.</li>
            <li>Dispatch automated email notifications regarding customer status and quotation updates.</li>
        </ul>

        <h2>4. Data Security & Storage</h2>
        <p>We implement enterprise-grade security controls. API tokens and sensitive credentials are encrypted and stored in secure backend databases. Access is strictly restricted to authenticated merchant sessions validated via Shopify Token Exchange and HMAC cryptographic signatures.</p>

        <h2>5. GDPR, CCPA & Shopify Compliance</h2>
        <p>We are fully compliant with Shopify's mandatory data privacy requirements:</p>
        <ul>
            <li><strong>Customer Data Requests:</strong> Merchants and customers may request an export of their stored personal data.</li>
            <li><strong>Customer Data Erasure:</strong> Upon receipt of a verified redaction request, all customer PII is purged or anonymized within <strong>5 business days</strong>.</li>
            <li><strong>Shop Redaction:</strong> When an app is uninstalled, all shop records and associated customer data are permanently purged within 48 hours following Shopify's `shop/redact` notification.</li>
        </ul>

        <h2>6. Contact Us</h2>
        <p>If you have any questions or concerns regarding our privacy practices or wish to exercise your data rights, please contact our privacy team at <a href="mailto:support@b2bhub.app" style="color: #008060;">support@b2bhub.app</a>.</p>
